import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const checks=[];
const ok=(name,pass)=>{checks.push([name,!!pass]);if(!pass)console.error('FAIL',name)};
const extreme=read('src/game/forest-extreme-world.ts');
const master=read('src/game/forest-master-world.ts');
const aquatic=read('src/game/aquatic.ts');
const state=read('src/game/adventure-state.ts');
const modern=read('src/game/modern.ts');
const gear=read('src/game/gear-model.ts');
const forestCss=read('src/forest-pilot.css');
const pad=read('src/adventure-action-pad.css');
const main=read('src/main.ts');
ok('RESET07 build id',extreme.includes('FG-EXTREME-RESET-07-20261105'));
ok('continuous terrain, no square-floor renderer',master.includes('surface-organic-heightfield')&&!master.includes('authoritative-walkable-floor'));
ok('visible cliff collision boundary',master.includes('authoritative-natural-cliff-boundary')&&!master.includes('authoritative-boundary-walls'));
ok('textured forest ground',master.includes("groundTexture('leaf')")&&master.includes("groundTexture('path')")&&master.includes("groundTexture('stone')"));
ok('water follows explicit carved volume',master.includes('waterfall-valley-deep-water-volume')&&master.includes('waterfall-upstream-stream')&&master.includes('waterfall-downstream-river'));
ok('forest ecology pass',master.includes('solid-forest-canopy-tree')&&master.includes('soft-forest-undergrowth'));
ok('pilot physics terrain is pilotGround',aquatic.includes('if(layout.pilot)return pilotGround(x,y)'));
ok('pilot swimming uses explicit water depth',aquatic.includes('pilotWaterDepth(p.x,p.y)>.72'));
ok('dry guard chase route',state.includes('guardDryRoute')&&state.includes("pilotWaterDepth(x+.5,y+.5)>.18"));
ok('pet hovers above water',modern.includes("waterLevel+1.15")&&modern.includes("'hover-over-water'"));
ok('no Tap map label',!modern.includes('Tap map'));
ok('one 3-digit animal paw',gear.includes('binturong-paw-3digit-v7')&&gear.includes('paw-digit-${i+1}'));
// Exact model checks without relying on runtime Three.js.
ok('paw has loop for exactly three toes',gear.includes("const toeX=[-.052,0,.052]")&&gear.includes('for(let i=0;i<3;i++'));
ok('legacy glove blob removed',!gear.includes('paw-front-pad')&&!gear.includes('paw-single-volume')&&!gear.includes('paw-cuff'));
ok('forest header back/title hidden',forestCss.includes('.forest-pilot #exit-game')&&forestCss.includes('.playbar>div:nth-child(2)'));
ok('legacy forest action positioning removed',!forestCss.includes('.forest-pilot #jump-action{')&&!forestCss.includes('.forest-pilot #hit-action{'));
ok('single shared corner-centred action pad',pad.includes('ONE authoritative Adventure action pad')&&pad.includes('160px*.707107'));
ok('Extreme routing remains explicit',main.includes('extreme')||read('src/game/modern.ts').includes("options.difficulty==='extreme'"));
const failed=checks.filter(([,v])=>!v);console.log(`RESET07 audit ${checks.length-failed.length}/${checks.length}`);if(failed.length)process.exit(2);
